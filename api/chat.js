// Detect if user is asking about specific products
function extractProductQuery(messages) {
const lastMsg = messages[messages.length - 1]?.content?.toLowerCase() || '';
const productKeywords = ['food', 'treat', 'toy', 'bed', 'collar', 'leash', 'shampoo', 'litter', 'cage', 'carrier', 'supplement', 'medicine', 'tablet', 'brand', 'royal canin', 'hills', 'josera', 'purina', 'whiskas', 'pedigree', 'orijen', 'price', 'cost', 'aed', 'buy', 'have', 'stock', 'available', 'product', 'kibble', 'wet food', 'dry food'];
const hasProduct = productKeywords.some(k => lastMsg.includes(k));
if (!hasProduct) return null;
// Extract search query - use last message content cleaned up
const cleaned = lastMsg.replace(/[?!.,]/g, '').trim();
return cleaned.length > 3 ? cleaned : null;
}

async function searchProducts(query) {
try {
const url = `${LUIGISBOX_URL}?tracker_id=${LUIGISBOX_TRACKER}&q=${encodeURIComponent(query)}&size=5&f[]=type:item`;
const r = await fetch(url, { headers: { 'Accept': 'application/json' } });
const data = await r.json();
const hits = data?.results?.hits || [];
return hits.map(h => {
const a = h.attributes || {};
const name = a.title || h.url;
const price = a.price || null;
const brand = Array.isArray(a.brand) ? a.brand[0] : (a.brand || null);
const inStock = (a.availability || 0) > 0;
const url2 = Array.isArray(a.web_url) ? a.web_url[0] : (a.web_url || `https://petcornerdubai.com/${h.url}`);
const discount = Array.isArray(a.discount) ? a.discount[0] : (a.discount || '0');
const autoship = Array.isArray(a.autoship_status) ? a.autoship_status[0] : false;
return { name, price, brand, inStock, url: url2, discount, autoship };
}).filter(p => p.name && !p.name.startsWith('product-')).slice(0, 5);
} catch(e) { return []; }
}

